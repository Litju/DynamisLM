"""A1 request renderers (RES-832): representation arms, instruction arms and liquid ablations.

Every renderer is a pure function of one frozen case and one arm name. The principal factorial
is

    adaptation x representation x decoder = 2 x 2 x 2

with ``R-hist`` and ``R-op`` carrying scientifically equivalent information. Everything else is
a separate diagnostic intervention and is named as such in the frozen call manifest.

Information equivalence
-----------------------
``R-op`` is ``BoundRequest.model_request()``: per-observation metric, protocol and device
stable ids, the question, and the host's typed ``requested_claims`` (empty in the deployed host
path, so claim preservation must come from the question text).

``R-hist`` reproduces the A0.2 training field structure and free-text register: ``objective``
(the question verbatim), ``question``, a free-text ``measurement``, observations with human
protocol/device/processing labels, the A0.2 constant evidence strings, and a derived
``comparability_evidence`` sentence. The historical generator emitted only a
``processing_method`` label; per-observation human protocol and device labels are added here
*solely* so the two principal arms carry the same scientific information. Adding explicit
assistance instead of equivalence is the separate enriched arm ``E-op``.

No renderer ever receives the gold action. Gold is used only by the scorer, after every output
is committed, and never appears in a prompt or a prompt hash input.
"""

from __future__ import annotations

import functools
from pathlib import Path
from typing import Any

from scripts import a02_v3_contract as v3
from scripts import a1_cases

ROOT = Path(__file__).resolve().parents[1]
# A0.2 constant strings, reused verbatim so the historical register is faithful. None of them
# varies by case, so none of them carries case information.
AVAILABLE_EVIDENCE = ["Supplied fictional values, unit labels and observation times"]
MISSING_EVIDENCE = ["No intervention or causal identification design is supplied."]
FOOTBALL_CONTEXT = {
    "athlete": "SYNTHETIC player",
    "population": a1_cases.POPULATION_TEXT,
}
SOURCE_DOCUMENTATION = "Fictional observations generated by repository code."
PROTOCOL_TEMPLATE = "Fictional fixed protocol for {measurement}"

# Human-readable labels are one-to-one with the synthetic registry identities in this cohort.
METRIC_LABEL = {
    "cmj-height": "countermovement jump height",
    "sprint-10m-time": "10 m sprint time",
    "imtp-peak-force": "isometric mid-thigh pull peak force",
    "session-total-distance": "session total distance",
    "maximal-aerobic-speed": "maximal aerobic speed",
    "nordic-eccentric-peak-force": "Nordic eccentric peak force",
}
PROTOCOL_LABEL = {
    "cmj-standard": "standard countermovement jump protocol",
    "sprint-standard": "standard 10 m sprint protocol",
    "imtp-standard": "standard isometric mid-thigh pull protocol",
    "gps-standard": "standard GPS session protocol",
    "aerobic-standard": "standard incremental treadmill protocol",
    "nordic-standard": "standard Nordic hamstring protocol",
}
DEVICE_LABEL = {
    "force-platform": "force platform",
    "timing-gates": "dual timing gates",
    "gps-unit": "wearable GPS unit",
    "instrumented-treadmill": "instrumented treadmill",
    "nordic-load-cell-frame": "load-cell Nordic frame",
}
# Gold-blind, structurally A0.2-style objective. It names the stated measurement and nothing
# else: never an analysis class, an operation, an observation subset or a claim level.
OBJECTIVE_TEMPLATE = "Report the requested result for {measurement} for this synthetic athlete."

# D3 uses one constant, non-gold claim request for every case. It never discloses the case's
# gold claim levels; it only makes the typed field non-empty.
CONSTANT_CLAIM_REQUEST = {
    "measurement": ["OBSERVED_VALUE"],
    "relationship": [],
}


def _metric_key(stable_id: str) -> str:
    return stable_id.split(":")[2].split("@")[0]


def _human_measurement(case: dict[str, Any]) -> str:
    stated = case["stated_measurement"]
    if stated is None:
        keys = {row["measurement"] for row in case["observations"]}
        if len(keys) != 1:
            raise ValueError(f"{case['case_id']} has no single stated measurement")
        stated = keys.pop()
    return a1_cases.human_measurement(stated)


def _labels(case: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    start_rows = a1_cases.observation_rows(case)
    for row in start_rows:
        rows.append(
            {
                "measurement": METRIC_LABEL[_metric_key(row["measurement"])],
                "protocol": PROTOCOL_LABEL[_metric_key(row["protocol"])],
                "device": DEVICE_LABEL[_metric_key(row["device"])],
                "processing_method": "repository synthetic pipeline",
                "time": row["date"],
                "unit": row["unit"],
                "value": row["value"],
            }
        )
    return rows


def _roles(count: int) -> list[str]:
    return ["baseline" if index == 0 else f"follow-up {index}" for index in range(count)]


def comparability_sentence(case: dict[str, Any]) -> str:
    """Exact equality/inequality statement over the same tuples ``R-op`` exposes per row."""
    rows = _labels(case)
    devices = {row["device"] for row in rows}
    protocols = {row["protocol"] for row in rows}
    methods = {row["processing_method"] for row in rows}
    measurements = {row["measurement"] for row in rows}
    parts = []
    for name, values in (
        ("measurement", measurements),
        ("acquisition device", devices),
        ("protocol", protocols),
        ("processing method", methods),
    ):
        if len(values) == 1:
            parts.append(f"every observation shares the same {name}")
        else:
            parts.append(f"{name} differs between observations")
    return "; ".join(parts) + "."


def historical_request(case: dict[str, Any]) -> dict[str, Any]:
    rows = _labels(case)
    roles = _roles(len(rows))
    measurement = _human_measurement(case)
    return {
        "objective": case["question"],
        "question": case["question"],
        "measurement": measurement,
        "observations": [
            {
                "measurement": row["measurement"],
                "protocol": row["protocol"],
                "device": row["device"],
                "processing_method": row["processing_method"],
                "role": role,
                "time": row["time"],
                "unit": row["unit"],
                "value": row["value"],
            }
            for row, role in zip(rows, roles, strict=True)
        ],
        "available_evidence": list(AVAILABLE_EVIDENCE),
        "missing_evidence": list(MISSING_EVIDENCE),
        "comparability_evidence": comparability_sentence(case),
        "football_context": dict(FOOTBALL_CONTEXT),
        "protocol": PROTOCOL_TEMPLATE.format(measurement=measurement),
        "source_documentation": SOURCE_DOCUMENTATION,
    }


def operational_request(case: dict[str, Any]) -> dict[str, Any]:
    return a1_cases.deployed_request(case)


def enriched_request(case: dict[str, Any]) -> dict[str, Any]:
    """D2: ``R-op`` plus one fixed, gold-blind objective field. Disclosed as assistance."""
    request = operational_request(case)
    return {
        "objective": OBJECTIVE_TEMPLATE.format(measurement=_human_measurement(case)),
        **request,
    }


def humanised_request(case: dict[str, Any]) -> dict[str, Any]:
    """D4: ``R-op`` with every stable id replaced by its one-to-one human label."""
    request = operational_request(case)
    rows = []
    for row in request["observations"]:
        rows.append(
            {
                "date": row["date"],
                "measurement": METRIC_LABEL[_metric_key(row["measurement"])],
                "protocol": PROTOCOL_LABEL[_metric_key(row["protocol"])],
                "device": DEVICE_LABEL[_metric_key(row["device"])],
                "unit": row["unit"],
                "value": row["value"],
            }
        )
    return {**request, "observations": rows}


def constant_claims_request(case: dict[str, Any]) -> dict[str, Any]:
    """D3: ``R-op`` with one constant, non-gold ``requested_claims`` request."""
    request = operational_request(case)
    return {**request, "requested_claims": dict(CONSTANT_CLAIM_REQUEST)}


def restricted_request(case: dict[str, Any], keep: str) -> dict[str, Any]:
    """Restricted-input baseline requests. ``keep`` selects the only surviving component."""
    request = operational_request(case)
    if keep == "question":
        return {
            **request,
            "observations": [],
            "requested_claims": {"measurement": [], "relationship": []},
        }
    if keep == "observations":
        return {
            "question": "",
            "observations": request["observations"],
            "requested_claims": {"measurement": [], "relationship": []},
        }
    if keep == "metadata":
        rows = [
            {
                "measurement": row["measurement"],
                "protocol": row["protocol"],
                "device": row["device"],
            }
            for row in request["observations"]
        ]
        return {
            "question": "",
            "observations": rows,
            "requested_claims": {"measurement": [], "relationship": []},
        }
    raise ValueError(f"unknown restricted-input projection: {keep}")


# --------------------------------------------------------------------------- system prompts

SYSTEM_PROMPTS = {
    "S-hist": ROOT / "experiments/a02/system-action-development-v3.txt",
    "S-corrected": ROOT / "experiments/a1/system-action-corrected-v1.txt",
}
SYSTEM_PROMPT_LABEL = {
    "S-hist": "A0.2 shared system prompt (references objective and question)",
    "S-corrected": "corrected system prompt (drops the objective sentence; no other change)",
}


def system_prompt(name: str) -> str:
    return SYSTEM_PROMPTS[name].read_text(encoding="utf-8").rstrip("\n")


# --------------------------------------------------------------------------- arm catalogue


def request_for(arm: str, case: dict[str, Any]) -> dict[str, Any]:
    """The model-visible request for one diagnostic arm."""
    if "request" in case:
        # D6/D7 cases carry their exact request; it is already frozen in its own module.
        if arm not in {"R-op", "OP", "D7-probe", "D6-retrospective"}:
            raise ValueError(f"{case['case_id']} only supports its own frozen request")
        frozen: dict[str, Any] = case["request"]
        return frozen
    if arm in {"R-op", "OP"}:
        return operational_request(case)
    if arm in {"R-hist", "HIST"}:
        return historical_request(case)
    if arm == "E-op":
        return enriched_request(case)
    if arm == "D4-human":
        return humanised_request(case)
    if arm == "D3-constant-claims":
        return constant_claims_request(case)
    raise ValueError(f"unknown request arm: {arm}")


def prompt_label(arm: str) -> str:
    return {
        "R-op": "operational BoundRequest.model_request() representation",
        "R-hist": "A0.2 training representation, proven information-equivalent",
        "E-op": "R-op plus a fixed gold-blind objective field (enriched; separate intervention)",
        "D4-human": "R-op with human labels instead of registry stable ids",
        "D3-constant-claims": "R-op with one constant non-gold requested_claims request",
        "D7-probe": "restricted A0.2 HELDOUT projection (shortcut probe)",
        "D6-retrospective": "reconstructed RES-774 BoundRequest.model_request()",
    }[arm]


def request_sha256(request: dict[str, Any]) -> str:
    return v3.sha256(v3.canonical(request).encode())


# --------------------------------------------------------------------------- few-shot exemplars

# Fixed A0.2 TRAIN rows rendered in R-op. They are drawn from the training split the adapter
# already saw, never from the A1 cohort, and they are never a cohort case. D5 is disclosed as a
# prompt-length and few-shot intervention, not a scientific comparison.
FEWSHOT_ORDINALS = (611, 640, 1093)


@functools.lru_cache(maxsize=1)
def fewshot_exemplars() -> tuple[dict[str, Any], ...]:
    from scripts import a02_v3_decision as decision

    protocol = decision.load_protocol()
    training = protocol["data"]["training"]
    from scripts import a02_v3_synthetic as synthetic

    examples = synthetic.generate(training["split"], training["seed"], training["count"])
    rows = []
    for index in FEWSHOT_ORDINALS:
        example = examples[index]
        visible = v3.visible_request(example["request"])
        rows.append({"request": visible, "action": v3.format_action(example["gold_action"])})
    return tuple(rows)


def render_messages(
    request: dict[str, Any], system: str, fewshot: str = "0"
) -> list[dict[str, str]]:
    """Exact chat messages: the shared system prompt and the canonical untrusted request."""
    messages = [{"role": "system", "content": system_prompt(system)}]
    if fewshot == "3":
        for exemplar in fewshot_exemplars():
            messages.append(
                {"role": "user", "content": v3.canonical({v3.REQUEST_KEY: exemplar["request"]})}
            )
            messages.append({"role": "assistant", "content": exemplar["action"]})
    elif fewshot != "0":
        raise ValueError(f"unknown few-shot arm: {fewshot}")
    messages.append({"role": "user", "content": v3.canonical({v3.REQUEST_KEY: request})})
    return messages


def prompt_sha256(request: dict[str, Any], system: str, fewshot: str = "0") -> str:
    """Digest of the exact messages. The runner also records the tokenizer-level digest."""
    return v3.sha256(v3.canonical(render_messages(request, system, fewshot)).encode())
