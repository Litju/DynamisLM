"""Independent synthetic V3 scientific-action examples and leakage audit (RES-541).

Intent-first generation: each example starts from a structured intent spec (family, analysis
class, target claims, observation structure). Gold comes from that spec, with the operation
taken from the same registry authority as V3 gold (``a02_v3_contract.operation_for``). Request
text is rendered afterwards from template banks. TRAIN and HELDOUT banks are disjoint, and
HELDOUT adds measurements that never appear in TRAIN.

Everything is generated by repository code from scratch: no external, empirical, RES-407
protected or RES-424 data. The ten exposed A0.2 cases are read only to exclude them. Nothing
generated is committed; a split is reproducible from its seed and pinned by a manifest hash.
Generating examples authorizes no training.
"""

